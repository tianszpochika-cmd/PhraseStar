const declarations = (values: Record<string, string>) =>
  Object.entries(values).map(([name, value]) => `${name}:${value}`).join(";");

export function renderOfficialSiteV1Theme(): string {
  return `:root{${declarations({ ...common, ...light })}}` +
    `:root[data-theme="dark"]{${declarations(dark)}}` +
    `:root[data-theme="high-contrast"]{${declarations(highContrast)}}`;
}
